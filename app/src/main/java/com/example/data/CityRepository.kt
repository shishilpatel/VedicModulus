    fun getDefaultCity(): LocationData = CITIES.first()

    fun searchCities(query: String): List<LocationData> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return CITIES.take(10)
        return CITIES.filter {
            it.cityName.lowercase().contains(q) ||
            it.talukaOrTown.lowercase().contains(q) ||
            it.district.lowercase().contains(q) ||
            it.state.lowercase().contains(q)
        }
    }
